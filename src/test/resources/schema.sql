-- H2 copy of the GROCER.PUBLIC tables used by the MCP tools. Same column names as Snowflake.
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID         VARCHAR(10)  PRIMARY KEY,
    NAME                VARCHAR(200) NOT NULL,
    ALLERGENS           VARCHAR(200),
    DIET                VARCHAR(20)  NOT NULL,
    PRICE_TOLERANCE_PCT INT          NOT NULL
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID    VARCHAR(10)   PRIMARY KEY,
    NAME          VARCHAR(200)  NOT NULL,
    CATEGORY      VARCHAR(50)   NOT NULL,
    BRAND         VARCHAR(100)  NOT NULL,
    PRICE_GBP     DECIMAL(10,2) NOT NULL,
    PACK_SIZE     VARCHAR(20),
    ALLERGENS     VARCHAR(200),
    IS_VEGETARIAN BOOLEAN       NOT NULL,
    IS_VEGAN      BOOLEAN       NOT NULL,
    STORAGE       VARCHAR(20)   NOT NULL
);

CREATE TABLE ORDERS (
    ORDER_ID      VARCHAR(10) NOT NULL,
    CUSTOMER_ID   VARCHAR(10) NOT NULL,
    STORE_ID      VARCHAR(10) NOT NULL,
    DELIVERY_DATE DATE        NOT NULL,
    LINE_NO       INT         NOT NULL,
    PRODUCT_ID    VARCHAR(10) NOT NULL,
    QUANTITY      INT         NOT NULL,
    PRIMARY KEY (ORDER_ID, LINE_NO)
);

CREATE TABLE STOCK (
    STORE_ID   VARCHAR(10) NOT NULL,
    PRODUCT_ID VARCHAR(10) NOT NULL,
    QUANTITY   INT         NOT NULL,
    STATUS     VARCHAR(30) NOT NULL,
    PRIMARY KEY (STORE_ID, PRODUCT_ID)
);

CREATE TABLE SUBSTITUTION_HISTORY (
    SUBSTITUTION_ID       VARCHAR(10)  PRIMARY KEY,
    CUSTOMER_ID           VARCHAR(10)  NOT NULL,
    ORIGINAL_PRODUCT_ID   VARCHAR(10)  NOT NULL,
    SUBSTITUTE_PRODUCT_ID VARCHAR(10)  NOT NULL,
    OUTCOME               VARCHAR(20)  NOT NULL,
    REJECTION_REASON      VARCHAR(200),
    SUBSTITUTED_ON        DATE         NOT NULL
);
